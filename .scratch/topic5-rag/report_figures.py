"""Draw the two report figures from artifacts that already exist.

Nothing here measures anything: every series is read out of a generated CSV or a
generated JSON. The drawings live in `assets/report/` because `reports/` is
generated by `python -m ragqa aggregate` and hand-writing files into it would
break that rule.

    python .scratch/topic5-rag/report_figures.py

Sources, one per figure:

    fig1-abstention.png   reports/abstention/{dense,hybrid,rerank}-pr.csv
                          + the working points in working-points.json
    fig2-sweeps.png       reports/sweeps/{k,chunk,hops}.csv

Two figures were retired in the final pass, because their numbers are in tables
the report already prints and the space was needed for §3.3 and §3.5:
`fig2-error-classes.png` (the hand taxonomy is a 275-event table now, not a
two-cell bar chart) and `fig3-prompt-shape-cost.png` (five numbers, all in the
§3.7 table). The interval figure was retired earlier: `significance.csv` had a
degenerate [0, 0] for the retrieval rows, and MRR/nDCG still print `missing` by
design.

Font sizes are chosen for the printed width (`FIGURE_CM` in `md_to_docx.py` is
11.4 cm against a 7.4 in canvas, so a canvas font renders at ~0.61 of its size).
"""

from __future__ import annotations

import csv
import json
import pathlib

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "assets" / "report"
OUT.mkdir(parents=True, exist_ok=True)

INK = "#1f2933"
BAR = "#3b6ea5"
BAR2 = "#c47f3d"
GRID = "#d8dee4"
TICK = 11


def style(ax):
    ax.grid(True, color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(INK)
    ax.tick_params(colors=INK, labelsize=TICK)


def fig1_abstention():
    """One panel per score scale, with the calibrated working point marked."""
    points = json.loads(
        (ROOT / "reports" / "abstention" / "working-points.json").read_text(encoding="utf-8")
    )["modes"]
    panels = [
        ("dense", "dense (cosine)"),
        ("hybrid", "hybrid (RRF sum)"),
        ("rerank", "rerank (cross-encoder)"),
    ]
    fig, axes = plt.subplots(1, 3, figsize=(7.4, 2.55), sharey=True)
    for ax, (mode, title) in zip(axes, panels):
        rows = list(
            csv.DictReader(
                (ROOT / "reports" / "abstention" / f"{mode}-pr.csv").open(encoding="utf-8")
            )
        )
        t = [float(r["t"]) for r in rows]
        prec = [float(r["precision"]) for r in rows]
        rec = [float(r["recall"]) for r in rows]
        ax.plot(rec, prec, color=BAR, linewidth=1.4, marker="o", markersize=3.4)
        t_star = points[mode]["t"]
        best = min(range(len(t)), key=lambda i: abs(t[i] - t_star))
        ax.scatter([rec[best]], [prec[best]], s=70, facecolor="white",
                   edgecolor=BAR2, linewidth=1.5, zorder=5)
        ax.annotate(
            f"t={t_star:.4f}\nraw {points[mode]['raw_threshold']:.6f}",
            xy=(rec[best], prec[best]),
            xytext=(0.44, 0.07),
            textcoords="axes fraction",
            fontsize=9.5,
            color=BAR2,
        )
        ax.set_title(title, fontsize=13, color=INK)
        ax.set_xlabel("recall on answerable items", fontsize=11.5, color=INK)
        ax.set_xlim(-0.03, 1.06)
        ax.set_ylim(-0.03, 1.08)
        style(ax)
    axes[0].set_ylabel("precision of answered items", fontsize=11.5, color=INK)
    fig.tight_layout(pad=0.5)
    fig.savefig(OUT / "fig1-abstention.png", dpi=220)
    plt.close(fig)


def _sweep(family):
    rows = [
        r
        for r in csv.DictReader(
            (ROOT / "reports" / "sweeps" / f"{family}.csv").open(encoding="utf-8")
        )
        if r["status"] == "finished"
    ]
    return rows


def fig2_sweeps():
    """recall@k as bars; each point's CNY per 1,000 questions rides its tick label."""
    panels = [
        ("k", "depth: retrieval.k", "k"),
        ("chunk", "chunk size: chunk.size", "words"),
        ("hops", "hops: retrieval.hops", "hops"),
    ]
    fig, axes = plt.subplots(1, 3, figsize=(7.4, 2.35), sharey=True)
    for ax, (family, title, unit) in zip(axes, panels):
        rows = _sweep(family)
        labels = [str(int(float(r["x"]))) for r in rows]
        recall = [float(r["recall_at_k"]) for r in rows]
        money = [float(r["cny_per_1k"]) for r in rows]
        xs = list(range(len(rows)))
        ax.bar(xs, recall, color=BAR, width=0.66)
        for x, value in zip(xs, recall):
            ax.text(x, value + 0.02, f"{value:.3f}", ha="center", fontsize=10,
                    color=INK)
        ax.set_xticks(xs)
        ax.set_xticklabels([f"{lab}\n¥{cost:.2f}" for lab, cost in zip(labels, money)],
                           fontsize=9.5)
        ax.set_ylim(0.0, 1.14)
        ax.set_xlim(-0.55, len(rows) - 0.45)
        ax.set_title(title, fontsize=11.5, color=INK)
        ax.set_xlabel(unit + "  ·  ¥ per 1,000 questions", fontsize=9.5, color=INK)
        style(ax)
    axes[0].set_ylabel("recall@k", fontsize=10.5, color=INK)
    fig.tight_layout(pad=0.5)
    fig.savefig(OUT / "fig2-sweeps.png", dpi=220)
    plt.close(fig)


if __name__ == "__main__":
    fig1_abstention()
    fig2_sweeps()
    for path in sorted(OUT.glob("*.png")):
        print(path.relative_to(ROOT), path.stat().st_size, "bytes")
